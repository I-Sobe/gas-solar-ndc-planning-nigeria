"""
55_recover_grid_service_reliability.py -- TASK 53 2.6 (register L103).

Post-hoc recovery, from STORED diagnostics, of the canonical reliability (grid-service shortfall =
unserved + self-generation) that `horizon_reliability` / `worst_year_reliability` /
`annual_reliability_by_year` should have been. No solve. The stored files are not modified: output is a
new CSV, `results/_recovered/grid_service_reliability_recovered.csv`.

Applies to every current diagnostics*.json that carries `unserved_twh_by_year`, `selfgen_twh_by_year`,
`demand_twh_by_year` and the old `horizon_reliability` (81 files at TASK 53: the NDC, EaaS, baseline and gate
families). The 81 `baseline_sliced` anchor-family files use a different schema (no demand series, no
reliability field) and are reported as not applicable. FIN-3, GAS-3 and POL-1 CSVs carry no self-generation
by year and are regenerated by the epoch's re-run instead.
"""
import csv
import glob
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.optimize_experiments import compute_grid_service_metrics  # the canonical definition


def main():
    out_dir = ROOT / "results" / "_recovered"
    out_dir.mkdir(parents=True, exist_ok=True)
    rows, n_na = [], 0
    for f in sorted(glob.glob(str(ROOT / "results" / "**" / "diagnostics*.json"), recursive=True)):
        rel = Path(f).relative_to(ROOT)
        if any(part.startswith("_") for part in rel.parts[1:-1]) or rel.parts[1] == "_recovered":
            continue                     # superseded snapshot directories
        d = json.load(open(f))
        need = ("unserved_twh_by_year", "selfgen_twh_by_year", "demand_twh_by_year", "horizon_reliability")
        if not all(k in d for k in need):
            n_na += 1
            continue
        dem = {int(y): float(v) for y, v in d["demand_twh_by_year"].items()}
        uns = {int(y): float(v) for y, v in d["unserved_twh_by_year"].items()}
        sg = {int(y): float(v) for y, v in d["selfgen_twh_by_year"].items()}
        m = compute_grid_service_metrics(dem, uns, sg)
        rows.append({
            "file": str(rel),
            "horizon_reliability_as_stored": d["horizon_reliability"],
            "grid_service_reliability_horizon_recovered": m["grid_service_reliability_horizon"],
            "grid_service_reliability_worst_year_recovered": m["grid_service_reliability_worst_year"],
            "grid_shortfall_total_twh": m["grid_shortfall_total_twh"],
            "unserved_total_twh": sum(uns.values()),
            "selfgen_total_twh": sum(sg.values()),
            "demand_total_twh": sum(dem.values()),
        })
    path = out_dir / "grid_service_reliability_recovered.csv"
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    lo = min(r["grid_service_reliability_horizon_recovered"] for r in rows)
    below = sum(1 for r in rows if r["grid_service_reliability_horizon_recovered"] < 1 - 1e-12)
    print(f"{len(rows)} diagnostics files recovered, {n_na} without the needed series; wrote {path}")
    print(f"stored horizon_reliability == 1.0 in {sum(1 for r in rows if r['horizon_reliability_as_stored'] == 1.0)} of them; "
          f"recovered horizon value < 1 in {below}; minimum recovered horizon value {lo:.6f}")


if __name__ == "__main__":
    main()

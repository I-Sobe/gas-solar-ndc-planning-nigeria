"""53_report_horizon_rebuild.py -- tabulate the eight horizon/rebuild cells against the (2045, same life) baseline. Reads only."""
import glob, json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
cells = {}
for f in glob.glob(str(ROOT / "results" / "horizon_rebuild" / "summary__*.json")):
    j = json.load(open(f)); cells[(j["end_year"], j["storage_life"])] = j
need = [(2045, 15.0), (2050, 15.0), (2051, 15.0), (2052, 15.0), (2053, 15.0), (2054, 15.0), (2045, 30.0), (2054, 30.0)]
miss = [c for c in need if c not in cells]
if miss: sys.exit(f"missing cells: {miss}")
L = ["# Horizon / in-horizon rebuild isolation (generated by scripts/53_report_horizon_rebuild.py)", "",
     "| end year | storage life | npv (USD) | max abs diff to 2045 plan vs (2045, same life): solar MW | storage MWh | gas MW | first year of difference |", "|---|---|---|---|---|---|---|"]
for k in need:
    j, b = cells[k], cells[(2045, k[1])]
    d = {n: [abs(p - q) for p, q in zip(j[n], b[n])] for n in ("solar_add_mw", "storage_add_mwh", "gas_add_mw")}
    first = min([y for y, *ds in zip(j["years_to_2045"], *d.values()) if max(ds) > 1e-6] or [None], default=None) if any(max(x) > 1e-6 for x in d.values()) else None
    L.append(f"| {k[0]} | {k[1]:g} | {j['npv_total_cost_usd']:.2f} | {max(d['solar_add_mw']):.4f} | {max(d['storage_add_mwh']):.4f} | {max(d['gas_add_mw']):.4f} | {first} |")
a = cells[(2054, 15.0)].get("anchor_check")
L += ["", f"Anchor check (2054, life 15): {a}", ""]
(ROOT / "docs" / "task_log_52_horizon_rebuild_results.md").write_text("\n".join(L) + "\n")
print("\n".join(L))

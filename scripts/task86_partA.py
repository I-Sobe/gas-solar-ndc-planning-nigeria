"""TASK 86 Part A: read-only inventory of docs/chapters/appendix_{a..d}.md.
Writes three listings to the directory given as argv[1]; prints summary counts."""
import re, sys, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
OUT = Path(sys.argv[1]); OUT.mkdir(parents=True, exist_ok=True)
APP = {k: (ROOT / f"docs/chapters/appendix_{k.lower()}.md").read_text(encoding="utf-8").split("\n") for k in "ABCD"}
FIND = (ROOT / "docs/findings_frozen.md").read_text(encoding="utf-8")
REG = (ROOT / "docs/limitations_register.md").read_text(encoding="utf-8")

# ---------------- A.3 figures
NUM = re.compile(r"(?<![\w./-])[-+−]?\d[\d,]*(?:\.\d+)?(?:[eE][-+]?\d+)?%?(?![\w-])")
SKIP_CTX = re.compile(r"\b(L\d+|F-\d+|[0-9a-f]{7,40})\b")
def figures(lines):
    out = []
    for i, ln in enumerate(lines, 1):
        s = re.sub(r"`[^`]*\.(?:py|md|csv|json|sh|yml|yaml)[^`]*`", lambda m: " " * len(m.group(0)), ln)  # file names / file:line
        s = re.sub(r"\b[LF]-?\d+\b", lambda m: " " * len(m.group(0)), s)
        s = re.sub(r"\b\d{4}-\d{2}-\d{2}\b", lambda m: " " * len(m.group(0)), s)
        s = re.sub(r"\b[0-9a-f]{7,40}\b", lambda m: " " * len(m.group(0)), s)
        s = re.sub(r"^#+ .*", lambda m: " " * len(m.group(0)), s)   # headings (entry ids)
        for m in NUM.finditer(s):
            tok = m.group(0)
            if re.fullmatch(r"\d{1,2}", tok) and not tok.endswith("%"):
                continue   # bare 1-2 digit integers: list numbers, row ids, small counts (counted separately)
            ctx = re.sub(r"\s+", " ", ln[max(0, m.start() - 55): m.end() + 35]).strip()
            out.append((i, tok, ctx))
    return out

OLD = {"central objective 24,986,620,949": r"24,986,620,949|24\.987|24,986",
 "solar 2045 19,241": r"19,24[01]", "gas 646": r"\b646\b", "storage 2045 37,414": r"37,41[45]",
 "capital share 43.80": r"43\.80?%?", "fuel share 30.10": r"30\.1\d?%", "O&M share 26.10": r"26\.1\d?%",
 "public solar capital share 22.2": r"22\.2%", "gross capex 46.8": r"46\.8", "gas_avail_observed 0.295": r"0\.295\b",
 "unconstrained requirement 8,723,252,062": r"8,723,252,06|8\.72\d", "B* overstatement 17.8": r"17\.8%",
 "suite 87 / 80/6/1": r"\b87\b assert|80 pass|80/6/1|\b80\b.{0,20}\b6\b.{0,20}\b1\b", "VSS 7.244": r"7\.244|7,244",
 "F-43 0.8125": r"0\.8125", "limitations count 83/82/62/63/147": r"\b(83|82|62|63|147|148)\b (of|entries|limitations|register)|of (83|82|147|148)\b"}

with open(OUT / "A3_figures.md", "w", encoding="utf-8") as f:
    f.write("# TASK 86 A.3 — every numeric figure in Appendices A to D\n\nGenerated by `scripts/task86_partA.py`. Columns: line, figure, context (55 chars before, 35 after). The *quantity* is the context; it is not judged stale here. Excluded from the token list: bare one- and two-digit integers without a % sign, L-/F-numbers, ISO dates, hex hashes, file names and `file:line` locators, and headings.\n")
    summ = {}
    for k, lines in APP.items():
        fg = figures(lines)
        summ[k] = (len(fg), len({t for _, t, _ in fg}))
        f.write(f"\n## Appendix {k}: {len(fg)} figure occurrences, {len({t for _, t, _ in fg})} distinct\n\n| line | figure | context |\n|---|---|---|\n")
        for i, t, c in fg:
            f.write(f"| {i} | {t} | {c.replace('|', '/')} |\n")
    f.write("\n## Part B.1 guide: lines where an 'old' value from the brief's table appears\n\n| appendix | line | pattern | text |\n|---|---|---|---|\n")
    hits = {}
    for k, lines in APP.items():
        for i, ln in enumerate(lines, 1):
            for name, pat in OLD.items():
                if re.search(pat, ln):
                    hits.setdefault((k, name), []).append(i)
                    f.write(f"| {k} | {i} | {name} | {re.sub(chr(10),' ',ln)[:150].replace('|','/')} |\n")
print("A.3 figure occurrences (appendix: occurrences, distinct):", summ)
print("A.3 old-value pattern hits:")
for (k, name), v in sorted(hits.items()):
    print(f"  {k} {name}: {len(v)} lines {v[:8]}{'...' if len(v) > 8 else ''}")
for name in OLD:
    if not any(n == name for (_, n) in hits):
        print("  NO HIT anywhere:", name)

# ---------------- A.4 claims
KEY = re.compile(r"second[- ]largest|largest (single )?lever|lever|rank|\bbinds?\b|binding|invariant|identical|unchanged|shadow price|\bdual\b|"
                 r"\bworth\b|\d+ (assertions|entries|limitations|findings)|not measured|could not be determined|undeterminable|"
                 r"conversion|financing (never|does not|changes)|self-generation|carbon price|tighten|inversion|retirement|ccgt_efficiency|"
                 r"gas_build|gas build|never changes|does not change|nothing|nowhere|always|in every|at every|every (arm|case|cell)", re.I)
def sentences(lines):
    para, start = [], None
    for i, ln in enumerate(lines, 1):
        if ln.strip() == "" or ln.startswith(("|", "#", "```")):
            if para:
                yield start, " ".join(para); para = []
            if ln.startswith("|"):
                yield i, ln
            continue
        if not para: start = i
        para.append(ln.strip())
    if para: yield start, " ".join(para)
with open(OUT / "A4_claims.md", "w", encoding="utf-8") as f:
    f.write("# TASK 86 A.4 — candidate claim sentences\n\nKeyword-selected (first pass) from prose and table rows of each appendix; Part A's reading of which bear on the re-derivation is in the log. Format: appendix:line | sentence (first 300 chars).\n")
    cnt = {}
    for k, lines in APP.items():
        n = 0
        f.write(f"\n## Appendix {k}\n\n")
        for st, text in sentences(lines):
            for s in re.split(r"(?<=[.!?])\s+(?=[A-Z`*(])", text):
                if KEY.search(s) and len(s) > 25:
                    f.write(f"- {k}:{st} | {s[:300]}\n"); n += 1
        cnt[k] = n
print("A.4 candidate sentences:", cnt)

# ---------------- A.5 cross-references
fnums = set(re.findall(r"^#{1,3} (F-\d+)", FIND, re.M))
lnums = {}
for m in re.finditer(r"^#{1,3} (L\d+)\b(.*)$", REG, re.M):
    lnums[m.group(1)] = m.group(2)
paths_exist = lambda p: (ROOT / p).exists() or bool(list(ROOT.glob(p)))
resdirs = " ".join(str(p.relative_to(ROOT)) for p in (ROOT / "results").rglob("*") if p.name.startswith(("arms_", "ARMS")) or "__" in p.name)
with open(OUT / "A5_xrefs.md", "w", encoding="utf-8") as f:
    f.write("# TASK 86 A.5 — cross-references from the appendices\n\n")
    tot = {}
    for k, lines in APP.items():
        F, Lr, S, H, P = {}, {}, {}, {}, {}
        for i, ln in enumerate(lines, 1):
            for m in re.finditer(r"\bF-\d+[a-z]?\b", ln): F.setdefault(m.group(0), []).append(i)
            if not ln.startswith("### L"):
                for m in re.finditer(r"(?<![\w-])L\d{1,3}\b", ln): Lr.setdefault(m.group(0), []).append(i)
            for m in re.finditer(r"(?:§|Section |Chapter )\d+(?:\.\d+)*", ln): S.setdefault(m.group(0), []).append(i)
            for m in re.finditer(r"(?:arms_|__)[0-9a-f]{8}\b", ln): H.setdefault(m.group(0), []).append(i)
            for m in re.finditer(r"`?((?:results|logs|docs|scripts|src|data)/[\w./*{},-]+)`?", ln): P.setdefault(m.group(1).rstrip(".,;:)"), []).append(i)
        tot[k] = (len(F), len(Lr), len(S), len(H), len(P))
        f.write(f"## Appendix {k}\n\n**F-numbers ({len(F)} distinct)**\n\n")
        for x, v in sorted(F.items(), key=lambda kv: int(re.search(r"\d+", kv[0]).group())):
            base = re.match(r"F-\d+", x).group(0)
            f.write(f"- {x}: lines {v[:12]}{'...' if len(v)>12 else ''} — {'target exists' if base in fnums else 'NO such heading in findings_frozen.md'}\n")
        f.write(f"\n**L-numbers cited in body text, excluding the entry's own heading ({len(Lr)} distinct)**\n\n")
        for x, v in sorted(Lr.items(), key=lambda kv: int(kv[0][1:])):
            f.write(f"- {x}: lines {v[:12]}{'...' if len(v)>12 else ''} — {'in register: ' + lnums[x].strip()[:70] if x in lnums else 'NOT a register heading'}\n")
        f.write(f"\n**Section/chapter references ({len(S)} distinct)**\n\n")
        for x, v in sorted(S.items()): f.write(f"- {x}: lines {v[:12]}{'...' if len(v)>12 else ''}\n")
        f.write(f"\n**Result files by hash ({len(H)} distinct)**\n\n")
        for x, v in sorted(H.items()):
            h = x[-8:]
            hit = [p for p in resdirs.split() if h in p][:2]
            f.write(f"- {x}: lines {v[:12]} — {'exists: ' + ', '.join(hit) if hit else 'no results/ path carries this hash'}\n")
        f.write(f"\n**Paths ({len(P)} distinct)**\n\n")
        for x, v in sorted(P.items()):
            f.write(f"- `{x}`: lines {v[:10]}{'...' if len(v)>10 else ''} — {'exists' if paths_exist(x) else 'MISSING'}\n")
        f.write("\n")
print("A.5 distinct (F, L, section, hash, path) per appendix:", tot)
print("findings headings:", len(fnums), "register headings:", len(lnums))

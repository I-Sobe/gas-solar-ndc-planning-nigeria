"""
51_report_capital_window.py -- TASK 51 M1: tabulate the six capital-window
cells (results/capital_window/summary__*.json) as deltas against 'advance'.
Reads only; writes docs/task_log_51_capital_window_results.md and prints it.
No solve. Run after scripts/run_capital_window.sh.
"""
import glob
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "task_log_51_capital_window_results.md"
CELLS = [(c, w) for c in ("unconstrained", "moderate")
         for w in ("advance", "arrears", "due_crf")]
SPLIT_TOL = 1e-6   # relative; a split "moves" if total concessional volume differs by more


def load():
    d = {}
    for f in glob.glob(str(ROOT / "results" / "capital_window" / "summary__*.json")):
        j = json.load(open(f))
        d[(j["capital_case"], j["capital_window_case"])] = j
    missing = [c for c in CELLS if c not in d]
    if missing:
        sys.exit(f"missing cells: {missing}")
    return d


def main():
    d = load()
    L = ["# TASK 51 M1 -- capital-window measurement: results", "",
         "Generated by `scripts/51_report_capital_window.py` from "
         "`results/capital_window/summary__*.json`. Verification artefact, "
         "not a thesis finding.", ""]
    a = d[("unconstrained", "advance")]["anchor_check"]
    L += ["## Regression (cell 1 against the central anchor)", "", "```", json.dumps(a, indent=2), "```", ""]

    L += ["## Objective and capital charge", "",
          "| capital_case | window | npv (USD) | d vs advance (USD) | d % | C^cap (USD) | C^cap share | conversion charge (USD) | conv share |",
          "|---|---|---|---|---|---|---|---|---|"]
    for c, w in CELLS:
        j, b = d[(c, w)], d[(c, "advance")]
        dn = j["npv_total_cost_usd"] - b["npv_total_cost_usd"]
        L.append(f"| {c} | {w} | {j['npv_total_cost_usd']:.2f} | {dn:.2f} | "
                 f"{100*dn/b['npv_total_cost_usd']:.4f} | {j['capital_charge_total_npv_usd']:.2f} | "
                 f"{100*j['capital_charge_share_of_objective']:.3f}% | "
                 f"{j['capital_charge_components_npv_usd']['conversion']:.2f} | "
                 f"{100*j['conversion_charge_share_of_objective']:.3f}% |")
    L += ["", "C^cap components (USD, NPV):", "",
          "| capital_case | window | public solar | EaaS solar | gas | storage | rebuild | conversion |",
          "|---|---|---|---|---|---|---|---|"]
    for c, w in CELLS:
        k = d[(c, w)]["capital_charge_components_npv_usd"]
        L.append(f"| {c} | {w} | " + " | ".join(f"{k[x]:.2f}" for x in
                 ("public_solar", "eaas_solar", "gas", "storage", "rebuild", "conversion")) + " |")

    L += ["", "## Physical plan", "",
          "| capital_case | window | solar to 2045 (MW) | solar to 2054 (MW) | d solar 2054 vs advance | storage 2045 (MWh) | storage 2054 (MWh) | d storage 2054 |",
          "|---|---|---|---|---|---|---|---|"]
    for c, w in CELLS:
        j, b = d[(c, w)], d[(c, "advance")]
        L.append(f"| {c} | {w} | {j['solar_cumulative_to_2045_mw']:.3f} | {j['solar_cumulative_to_2054_mw']:.3f} | "
                 f"{j['solar_cumulative_to_2054_mw']-b['solar_cumulative_to_2054_mw']:.3f} | "
                 f"{j['storage_capacity_2045_mwh']:.2f} | {j['storage_capacity_2054_mwh']:.2f} | "
                 f"{j['storage_capacity_2054_mwh']-b['storage_capacity_2054_mwh']:.2f} |")
    years = sorted(int(y) for y in d[CELLS[0]]["decision_variables"]["solar_add_mw_by_year"])
    L += ["", "solar_add_mw_by_year (MW):", "",
          "| year | " + " | ".join(f"{c[:3]}/{w}" for c, w in CELLS) + " |", "|---" * 7 + "|"]
    for y in years:
        L.append(f"| {y} | " + " | ".join(
            f"{d[k]['decision_variables']['solar_add_mw_by_year'][str(y)]:.3f}" for k in CELLS) + " |")
    L += ["", "storage_add_mwh_by_year (MWh):", "",
          "| year | " + " | ".join(f"{c[:3]}/{w}" for c, w in CELLS) + " |", "|---" * 7 + "|"]
    for y in years:
        L.append(f"| {y} | " + " | ".join(
            f"{d[k]['decision_variables']['storage_add_mwh_by_year'][str(y)]:.2f}" for k in CELLS) + " |")

    L += ["", "## Concessional split", "",
          "| capital_case | window | total concessional volume (USD) | d vs advance | vintages with volume > 0 | max share |",
          "|---|---|---|---|---|---|"]
    moved = {}
    for c, w in CELLS:
        j, b = d[(c, w)], d[(c, "advance")]
        tv, bv = j["concessional_volume_total_usd"], b["concessional_volume_total_usd"]
        vint = [y for y, v in j["concessional_volume_by_vintage_usd"].items() if v > 0]
        moved[(c, w)] = abs(tv - bv) > SPLIT_TOL * max(1.0, abs(bv)) or \
            j["concessional_volume_by_vintage_usd"] != b["concessional_volume_by_vintage_usd"]
        L.append(f"| {c} | {w} | {tv:.2f} | {tv-bv:.2f} | {', '.join(vint)} | "
                 f"{max(j['concessional_share_by_vintage'].values()):.6f} |")
    L += ["", "Concessional volume by vintage and share (non-zero vintages only):", ""]
    for c, w in CELLS:
        j = d[(c, w)]
        nz = {y: (round(v, 2), round(j['concessional_share_by_vintage'][y], 6))
              for y, v in j["concessional_volume_by_vintage_usd"].items() if v > 0}
        L.append(f"- {c}/{w}: {nz}")
    L += ["", "**Discriminating observation** (split moves under due_crf and not under arrears):", ""]
    for c in ("unconstrained", "moderate"):
        L.append(f"- {c}: split moves under arrears = {moved[(c,'arrears')]}; under due_crf = {moved[(c,'due_crf')]}.")

    L += ["", "## Public budget and concessional envelope", "",
          "| capital_case | window | budget body | budget slack | budget binding | budget dual | envelope slack | envelope binding | envelope dual |",
          "|---|---|---|---|---|---|---|---|---|"]
    for c, w in CELLS:
        j = d[(c, w)]
        pb, ev = j["public_budget_constraint"], j["concessional_envelope_constraint"]
        f = lambda x, k: ("n/a" if x is None else x[k])
        L.append(f"| {c} | {w} | {f(pb,'body')} | {f(pb,'slack')} | {f(pb,'binding')} | {f(pb,'dual')} | "
                 f"{f(ev,'slack')} | {f(ev,'binding')} | {f(ev,'dual')} |")
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nWritten: {OUT}")


if __name__ == "__main__":
    main()
